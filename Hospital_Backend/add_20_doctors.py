def main():
    if len(DOCTORS) != 20:
        raise ValueError("В списке должно быть ровно 20 врачей")

    with transaction.atomic():
        specs = {}
        added_specs = 0
        for name, description in SPECIALIZATIONS.items():
            spec, created = Specialization.objects.get_or_create(
                name=name,
                defaults={"description": description},
            )
            specs[name] = spec
            added_specs += int(created)

        added_doctors = 0
        added_schedules = 0
        for number, (first, last, patronymic, spec_name, years, price, start, end) in enumerate(DOCTORS):
            doctor, created = Doctor.objects.get_or_create(
                first_name=first,
                last_name=last,
                patronymic=patronymic,
                specialization=specs[spec_name],
                defaults={
                    "experience_years": years,
                    "price": Decimal(price),
                },
            )
            added_doctors += int(created)

            # Каждому врачу — пять дней работы в неделю.
            # Часть врачей принимает пн–пт, часть вт–сб.
            weekdays = range(1, 6) if number % 4 == 3 else range(0, 5)
            for day in weekdays:
                _, created_schedule = Schedule.objects.get_or_create(
                    doctor=doctor,
                    day_of_week=day,
                    start_time=time(start, 0),
                    end_time=time(end, 0),
                )
                added_schedules += int(created_schedule)
            print(f"{'ДОБАВЛЕН' if created else 'УЖЕ ЕСТЬ'}: {doctor} — {spec_name}")

    print("\nИмпорт завершён!")
    print(f"Новых специализаций: {added_specs}")
    print(f"Новых врачей: {added_doctors} из 20")
    print(f"Новых строк расписания: {added_schedules}")
    print("Проверь: http://127.0.0.1:8000/api/doctors/")
    print("Фронтенд автоматически покажет врачей после обновления страницы.")


if __name__ == "__main__":
    main()
